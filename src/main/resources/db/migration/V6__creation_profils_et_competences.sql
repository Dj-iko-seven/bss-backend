CREATE TABLE specialites_professionnelles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(150) NOT NULL UNIQUE,
    description TEXT,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE profils_citoyens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL UNIQUE REFERENCES utilisateurs(id),
    prenom VARCHAR(100) NOT NULL,
    nom VARCHAR(100) NOT NULL,
    telephone VARCHAR(30),
    date_naissance DATE,
    province_id BIGINT REFERENCES provinces(id),
    commune_id BIGINT REFERENCES communes(id),
    zone_id BIGINT REFERENCES zones(id),
    colline_id BIGINT REFERENCES collines(id),
    document_photo_profil_id BIGINT REFERENCES documents(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE specialites_citoyens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profil_citoyen_id BIGINT NOT NULL REFERENCES profils_citoyens(id),
    specialite_id BIGINT NOT NULL REFERENCES specialites_professionnelles(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (profil_citoyen_id, specialite_id)
);

CREATE TABLE competences_utilisateurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    libelle VARCHAR(200) NOT NULL,
    niveau VARCHAR(30) CHECK (niveau IN ('DEBUTANT', 'INTERMEDIAIRE', 'AVANCE', 'EXPERT')),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE profils_entreprises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL UNIQUE REFERENCES utilisateurs(id),
    nom_officiel VARCHAR(255) NOT NULL,
    nom_commercial VARCHAR(255),
    numero_enregistrement VARCHAR(100),
    identifiant_fiscal VARCHAR(100),
    description_activite TEXT,
    telephone_entreprise VARCHAR(30),
    email_entreprise VARCHAR(255),
    adresse VARCHAR(255),
    localisation_id BIGINT REFERENCES localisations(id),
    statut_verification VARCHAR(30) NOT NULL DEFAULT 'EN_ATTENTE' CHECK (statut_verification IN ('EN_ATTENTE', 'EN_EXAMEN', 'VERIFIEE', 'REJETEE', 'SUSPENDUE')),
    document_logo_id BIGINT REFERENCES documents(id),
    est_supprime BOOLEAN NOT NULL DEFAULT FALSE,
    date_suppression TIMESTAMPTZ,
    supprime_par BIGINT REFERENCES utilisateurs(id),
    cree_par BIGINT REFERENCES utilisateurs(id),
    modifie_par BIGINT REFERENCES utilisateurs(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE verifications_entreprises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profil_entreprise_id BIGINT NOT NULL REFERENCES profils_entreprises(id),
    verificateur_utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    resultat VARCHAR(30) NOT NULL CHECK (resultat IN ('CONFORME', 'NON_CONFORME', 'COMPLEMENT_REQUIS')),
    observations TEXT,
    date_verification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE decisions_verification_entreprises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profil_entreprise_id BIGINT NOT NULL REFERENCES profils_entreprises(id),
    decideur_utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    decision VARCHAR(30) NOT NULL CHECK (decision IN ('APPROUVEE', 'REJETEE', 'SUSPENDUE')),
    motif TEXT,
    date_decision TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TRIGGER trg_profils_citoyens_date_modification BEFORE UPDATE ON profils_citoyens FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_competences_utilisateurs_date_modification BEFORE UPDATE ON competences_utilisateurs FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_profils_entreprises_date_modification BEFORE UPDATE ON profils_entreprises FOR EACH ROW EXECUTE FUNCTION maj_date_modification();

CREATE INDEX idx_profils_citoyens_utilisateur ON profils_citoyens(utilisateur_id);
CREATE INDEX idx_competences_utilisateurs_utilisateur ON competences_utilisateurs(utilisateur_id);
CREATE INDEX idx_profils_entreprises_statut ON profils_entreprises(statut_verification);
CREATE INDEX idx_verifications_entreprises_profil ON verifications_entreprises(profil_entreprise_id);
CREATE INDEX idx_decisions_verification_entreprises_profil ON decisions_verification_entreprises(profil_entreprise_id);
