CREATE TABLE demandes_assistance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(50) NOT NULL UNIQUE,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    institution_id BIGINT REFERENCES institutions_publiques(id),
    type_demande VARCHAR(30) NOT NULL CHECK (type_demande IN ('QUESTION', 'RECLAMATION', 'SIGNALEMENT')),
    titre VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    statut VARCHAR(30) NOT NULL DEFAULT 'NOUVELLE' CHECK (statut IN ('NOUVELLE', 'EN_ATTENTE', 'EN_COURS', 'RESOLUE', 'FERMEE')),
    date_cloture TIMESTAMPTZ,
    est_supprime BOOLEAN NOT NULL DEFAULT FALSE,
    date_suppression TIMESTAMPTZ,
    supprime_par BIGINT REFERENCES utilisateurs(id),
    cree_par BIGINT REFERENCES utilisateurs(id),
    modifie_par BIGINT REFERENCES utilisateurs(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE messages_assistance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demande_id BIGINT NOT NULL REFERENCES demandes_assistance(id),
    auteur_utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    contenu TEXT NOT NULL,
    est_interne BOOLEAN NOT NULL DEFAULT FALSE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pieces_jointes_assistance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demande_id BIGINT NOT NULL REFERENCES demandes_assistance(id),
    message_id BIGINT REFERENCES messages_assistance(id),
    document_id BIGINT NOT NULL REFERENCES documents(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (demande_id, document_id)
);

CREATE TABLE historique_statuts_assistance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demande_id BIGINT NOT NULL REFERENCES demandes_assistance(id),
    statut_precedent VARCHAR(30),
    statut_nouveau VARCHAR(30) NOT NULL,
    utilisateur_id BIGINT REFERENCES utilisateurs(id),
    date_changement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TRIGGER trg_demandes_assistance_date_modification BEFORE UPDATE ON demandes_assistance FOR EACH ROW EXECUTE FUNCTION maj_date_modification();

CREATE INDEX idx_demandes_assistance_utilisateur ON demandes_assistance(utilisateur_id);
CREATE INDEX idx_demandes_assistance_institution ON demandes_assistance(institution_id);
CREATE INDEX idx_demandes_assistance_statut ON demandes_assistance(statut);
CREATE INDEX idx_messages_assistance_demande ON messages_assistance(demande_id);
CREATE INDEX idx_pieces_jointes_assistance_demande ON pieces_jointes_assistance(demande_id);
CREATE INDEX idx_historique_statuts_assistance_demande ON historique_statuts_assistance(demande_id);
