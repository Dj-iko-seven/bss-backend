CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinataire_utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    type VARCHAR(80) NOT NULL,
    titre VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    canal VARCHAR(20) NOT NULL CHECK (canal IN ('APPLICATION', 'EMAIL', 'SMS', 'PUSH')),
    statut VARCHAR(20) NOT NULL DEFAULT 'EN_ATTENTE' CHECK (statut IN ('EN_ATTENTE', 'ENVOYE', 'ECHOUEE', 'LU')),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_envoi TIMESTAMPTZ,
    date_lecture TIMESTAMPTZ
);

CREATE TABLE preferences_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    type_notification VARCHAR(80) NOT NULL,
    canal VARCHAR(20) NOT NULL CHECK (canal IN ('APPLICATION', 'EMAIL', 'SMS', 'PUSH')),
    est_actif BOOLEAN NOT NULL DEFAULT TRUE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (utilisateur_id, type_notification, canal)
);

CREATE TABLE modeles_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(80) NOT NULL UNIQUE,
    langue_id BIGINT NOT NULL REFERENCES langues(id),
    objet VARCHAR(255) NOT NULL,
    corps TEXT NOT NULL,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE envois_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL REFERENCES notifications(id),
    canal VARCHAR(20) NOT NULL CHECK (canal IN ('APPLICATION', 'EMAIL', 'SMS', 'PUSH')),
    fournisseur VARCHAR(80),
    reference_fournisseur VARCHAR(255),
    statut VARCHAR(20) NOT NULL DEFAULT 'EN_ATTENTE' CHECK (statut IN ('EN_ATTENTE', 'ENVOYE', 'ECHOUEE')),
    tentatives INTEGER NOT NULL DEFAULT 0,
    erreur TEXT,
    date_envoi TIMESTAMPTZ
);

CREATE TABLE historique_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL REFERENCES notifications(id),
    action VARCHAR(80) NOT NULL,
    detail TEXT,
    date_action TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TRIGGER trg_preferences_notifications_date_modification BEFORE UPDATE ON preferences_notifications FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_modeles_notifications_date_modification BEFORE UPDATE ON modeles_notifications FOR EACH ROW EXECUTE FUNCTION maj_date_modification();

CREATE INDEX idx_notifications_destinataire ON notifications(destinataire_utilisateur_id);
CREATE INDEX idx_notifications_statut ON notifications(statut);
CREATE INDEX idx_preferences_notifications_utilisateur ON preferences_notifications(utilisateur_id);
CREATE INDEX idx_envois_notifications_notification ON envois_notifications(notification_id);
CREATE INDEX idx_historique_notifications_notification ON historique_notifications(notification_id);
