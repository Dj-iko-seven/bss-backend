CREATE TABLE types_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(60) NOT NULL UNIQUE,
    libelle VARCHAR(150) NOT NULL,
    description TEXT,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proprietaire_utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    type_document_id BIGINT NOT NULL REFERENCES types_documents(id),
    nom_original VARCHAR(255) NOT NULL,
    nom_interne VARCHAR(255) NOT NULL UNIQUE,
    type_mime VARCHAR(150) NOT NULL,
    taille BIGINT NOT NULL CHECK (taille > 0),
    empreinte_sha256 VARCHAR(64) NOT NULL,
    cle_stockage VARCHAR(512) NOT NULL UNIQUE,
    statut VARCHAR(30) NOT NULL DEFAULT 'DISPONIBLE' CHECK (statut IN ('DISPONIBLE', 'EN_COURS_ANALYSE', 'REJETE', 'ARCHIVE')),
    statut_antivirus VARCHAR(30) NOT NULL DEFAULT 'NON_VERIFIE' CHECK (statut_antivirus IN ('NON_VERIFIE', 'SAIN', 'INFECTE', 'INDISPONIBLE')),
    est_supprime BOOLEAN NOT NULL DEFAULT FALSE,
    date_suppression TIMESTAMPTZ,
    supprime_par BIGINT REFERENCES utilisateurs(id),
    cree_par BIGINT REFERENCES utilisateurs(id),
    modifie_par BIGINT REFERENCES utilisateurs(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_depot TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE regles_acces_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_document_id BIGINT NOT NULL REFERENCES types_documents(id),
    role_id BIGINT NOT NULL REFERENCES roles(id),
    institution_id BIGINT,
    action VARCHAR(30) NOT NULL CHECK (action IN ('CONSULTER', 'MODIFIER', 'SUPPRIMER', 'TELECHARGER')),
    est_autorise BOOLEAN NOT NULL DEFAULT TRUE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE NULLS NOT DISTINCT (type_document_id, role_id, institution_id, action)
);

CREATE TRIGGER trg_types_documents_date_modification BEFORE UPDATE ON types_documents FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_documents_date_modification BEFORE UPDATE ON documents FOR EACH ROW EXECUTE FUNCTION maj_date_modification();

CREATE INDEX idx_documents_proprietaire ON documents(proprietaire_utilisateur_id);
CREATE INDEX idx_documents_type ON documents(type_document_id);
CREATE INDEX idx_regles_acces_documents_type_role ON regles_acces_documents(type_document_id, role_id);

