CREATE TABLE institutions_publiques (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_officiel VARCHAR(255) NOT NULL,
    type_institution VARCHAR(100),
    ministere_rattachement VARCHAR(150),
    adresse VARCHAR(255),
    province_id BIGINT REFERENCES provinces(id),
    commune_id BIGINT REFERENCES communes(id),
    localisation_id BIGINT REFERENCES localisations(id),
    telephone VARCHAR(30),
    adresse_email VARCHAR(255),
    statut VARCHAR(30) NOT NULL DEFAULT 'ACTIF' CHECK (statut IN ('ACTIF', 'INACTIF', 'SUSPENDU')),
    est_supprime BOOLEAN NOT NULL DEFAULT FALSE,
    date_suppression TIMESTAMPTZ,
    supprime_par BIGINT REFERENCES utilisateurs(id),
    cree_par BIGINT REFERENCES utilisateurs(id),
    modifie_par BIGINT REFERENCES utilisateurs(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE regles_acces_documents ADD CONSTRAINT fk_regles_acces_documents_institution FOREIGN KEY (institution_id) REFERENCES institutions_publiques(id);

CREATE TABLE categories_services_publics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(60) NOT NULL UNIQUE,
    libelle VARCHAR(150) NOT NULL,
    description TEXT,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE services_publics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions_publiques(id),
    categorie_id BIGINT REFERENCES categories_services_publics(id),
    nom VARCHAR(255) NOT NULL,
    description TEXT,
    conditions_acces TEXT,
    cout NUMERIC(19, 4),
    devise VARCHAR(10) NOT NULL DEFAULT 'BIF',
    localisation_id BIGINT REFERENCES localisations(id),
    lien_officiel VARCHAR(512),
    statut VARCHAR(30) NOT NULL DEFAULT 'BROUILLON' CHECK (statut IN ('BROUILLON', 'PUBLIE', 'ARCHIVE', 'SUSPENDU')),
    date_publication TIMESTAMPTZ,
    est_supprime BOOLEAN NOT NULL DEFAULT FALSE,
    date_suppression TIMESTAMPTZ,
    supprime_par BIGINT REFERENCES utilisateurs(id),
    cree_par BIGINT REFERENCES utilisateurs(id),
    modifie_par BIGINT REFERENCES utilisateurs(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE procedures_services_publics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES services_publics(id),
    titre VARCHAR(255) NOT NULL,
    description TEXT,
    delai_traitement VARCHAR(100),
    cout NUMERIC(19, 4),
    devise VARCHAR(10) NOT NULL DEFAULT 'BIF',
    statut VARCHAR(30) NOT NULL DEFAULT 'BROUILLON' CHECK (statut IN ('BROUILLON', 'PUBLIE', 'ARCHIVE')),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE etapes_procedures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_id BIGINT NOT NULL REFERENCES procedures_services_publics(id),
    ordre_affichage INTEGER NOT NULL CHECK (ordre_affichage > 0),
    titre VARCHAR(255) NOT NULL,
    description TEXT,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE exigences_procedures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_id BIGINT NOT NULL REFERENCES procedures_services_publics(id),
    libelle VARCHAR(255) NOT NULL,
    description TEXT,
    est_obligatoire BOOLEAN NOT NULL DEFAULT TRUE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE documents_services_publics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_id BIGINT NOT NULL REFERENCES procedures_services_publics(id),
    document_id BIGINT NOT NULL REFERENCES documents(id),
    libelle VARCHAR(255),
    est_obligatoire BOOLEAN NOT NULL DEFAULT TRUE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (procedure_id, document_id)
);

CREATE TABLE horaires_services_publics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES services_publics(id),
    jour VARCHAR(20) NOT NULL CHECK (jour IN ('LUNDI', 'MARDI', 'MERCREDI', 'JEUDI', 'VENDREDI', 'SAMEDI', 'DIMANCHE')),
    heure_ouverture TIME,
    heure_fermeture TIME,
    est_ferme BOOLEAN NOT NULL DEFAULT FALSE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE contacts_services_publics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES services_publics(id),
    type_contact VARCHAR(30) NOT NULL CHECK (type_contact IN ('TELEPHONE', 'EMAIL', 'ADRESSE', 'AUTRE')),
    valeur VARCHAR(255) NOT NULL,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE historique_services_publics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES services_publics(id),
    action VARCHAR(100) NOT NULL,
    donnees_avant JSONB,
    donnees_apres JSONB,
    utilisateur_id BIGINT REFERENCES utilisateurs(id),
    date_action TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE informations_officielles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions_publiques(id),
    titre VARCHAR(255) NOT NULL,
    contenu TEXT NOT NULL,
    type_information VARCHAR(80),
    date_publication TIMESTAMPTZ,
    statut VARCHAR(20) NOT NULL DEFAULT 'BROUILLON' CHECK (statut IN ('BROUILLON', 'PUBLIE', 'ARCHIVE')),
    auteur_utilisateur_id BIGINT REFERENCES utilisateurs(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TRIGGER trg_institutions_publiques_date_modification BEFORE UPDATE ON institutions_publiques FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_categories_services_date_modification BEFORE UPDATE ON categories_services_publics FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_services_publics_date_modification BEFORE UPDATE ON services_publics FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_procedures_services_date_modification BEFORE UPDATE ON procedures_services_publics FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_informations_officielles_date_modification BEFORE UPDATE ON informations_officielles FOR EACH ROW EXECUTE FUNCTION maj_date_modification();

CREATE INDEX idx_institutions_province ON institutions_publiques(province_id);
