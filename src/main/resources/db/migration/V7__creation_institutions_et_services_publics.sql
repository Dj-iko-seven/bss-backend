CREATE INDEX idx_historique_services_service ON historique_services_publics(service_id);
CREATE INDEX idx_informations_officielles_institution ON informations_officielles(institution_id);

INSERT INTO categories_services_publics (code, libelle, description)
SELECT v.code, v.libelle, v.description
FROM (VALUES
    ('ETAT_CIVIL', 'Etat civil', 'Services d etat civil'),
    ('SANTE', 'Sante', 'Services de sante'),
    ('EDUCATION', 'Education', 'Services educatifs'),
    ('FISCALITE', 'Fiscalite', 'Services fiscaux'),
    ('COMMERCE', 'Commerce', 'Services commerciaux'),
    ('AUTRE', 'Autre', 'Autres services publics')
) AS v(code, libelle, description)
WHERE NOT EXISTS (SELECT 1 FROM categories_services_publics c WHERE c.code = v.code);
