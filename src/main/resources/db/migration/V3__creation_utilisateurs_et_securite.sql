CREATE TABLE langues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(8) NOT NULL UNIQUE CHECK (code IN ('FR', 'RN', 'EN', 'SW')),
    libelle VARCHAR(100) NOT NULL,
    est_defaut BOOLEAN NOT NULL DEFAULT FALSE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX idx_langues_une_seule_defaut ON langues(est_defaut) WHERE est_defaut;

CREATE TABLE utilisateurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_publique UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    adresse_email VARCHAR(255) NOT NULL UNIQUE,
    mot_de_passe VARCHAR(255) NOT NULL,
    telephone VARCHAR(30),
    statut_compte VARCHAR(30) NOT NULL DEFAULT 'ACTIF' CHECK (statut_compte IN ('ACTIF', 'SUSPENDU', 'DESACTIVE', 'SUPPRIME')),
    est_supprime BOOLEAN NOT NULL DEFAULT FALSE,
    date_suppression TIMESTAMPTZ,
    supprime_par BIGINT REFERENCES utilisateurs(id),
    cree_par BIGINT REFERENCES utilisateurs(id),
    modifie_par BIGINT REFERENCES utilisateurs(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE CHECK (code IN ('SUPER_ADMINISTRATEUR', 'ADMIN_PUBLIC', 'ENTREPRISE', 'CITOYEN')),
    libelle VARCHAR(100) NOT NULL,
    description TEXT,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(80) NOT NULL UNIQUE,
    libelle VARCHAR(150) NOT NULL,
    module VARCHAR(50) NOT NULL,
    description TEXT,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE utilisateurs_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    role_id BIGINT NOT NULL REFERENCES roles(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (utilisateur_id, role_id)
);

CREATE TABLE roles_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL REFERENCES roles(id),
    permission_id BIGINT NOT NULL REFERENCES permissions(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (role_id, permission_id)
);

CREATE TABLE sessions_utilisateurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    jti_hash VARCHAR(64) NOT NULL UNIQUE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_expiration TIMESTAMPTZ NOT NULL,
    date_deconnexion TIMESTAMPTZ,
    adresse_ip VARCHAR(45),
    appareil VARCHAR(255),
    est_revoquee BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE jetons_reinitialisation_mot_de_passe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    jeton_hash VARCHAR(64) NOT NULL UNIQUE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_expiration TIMESTAMPTZ NOT NULL,
    est_utilise BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE verifications_adresses_email (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    code_hash VARCHAR(64) NOT NULL,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_expiration TIMESTAMPTZ NOT NULL,
    est_verifie BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE verifications_telephones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    code_hash VARCHAR(64) NOT NULL,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_expiration TIMESTAMPTZ NOT NULL,
    est_verifie BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE preferences_langues_utilisateurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL UNIQUE REFERENCES utilisateurs(id),
    langue_id BIGINT NOT NULL REFERENCES langues(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE traductions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cle VARCHAR(200) NOT NULL,
    langue_id BIGINT NOT NULL REFERENCES langues(id),
    texte TEXT NOT NULL,
    contexte VARCHAR(100),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (cle, langue_id)
);

CREATE TRIGGER trg_utilisateurs_date_modification BEFORE UPDATE ON utilisateurs FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_roles_date_modification BEFORE UPDATE ON roles FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_permissions_date_modification BEFORE UPDATE ON permissions FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_preferences_langues_date_modification BEFORE UPDATE ON preferences_langues_utilisateurs FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_traductions_date_modification BEFORE UPDATE ON traductions FOR EACH ROW EXECUTE FUNCTION maj_date_modification();

CREATE INDEX idx_utilisateurs_statut_compte ON utilisateurs(statut_compte);
CREATE INDEX idx_sessions_utilisateurs_utilisateur ON sessions_utilisateurs(utilisateur_id);
CREATE INDEX idx_utilisateurs_roles_utilisateur ON utilisateurs_roles(utilisateur_id);
CREATE INDEX idx_roles_permissions_role ON roles_permissions(role_id);
CREATE INDEX idx_traductions_cle ON traductions(cle);

