CREATE TABLE pages_cms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    titre VARCHAR(255) NOT NULL,
    statut VARCHAR(20) NOT NULL DEFAULT 'BROUILLON' CHECK (statut IN ('BROUILLON', 'PUBLIE', 'ARCHIVE')),
    date_publication TIMESTAMPTZ,
    cree_par BIGINT REFERENCES utilisateurs(id),
    modifie_par BIGINT REFERENCES utilisateurs(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sections_cms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id BIGINT NOT NULL REFERENCES pages_cms(id),
    code VARCHAR(80) NOT NULL,
    titre VARCHAR(255),
    contenu TEXT,
    ordre_affichage INTEGER NOT NULL DEFAULT 0,
    est_visible BOOLEAN NOT NULL DEFAULT TRUE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (page_id, code)
);

CREATE TABLE cartes_cms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id BIGINT NOT NULL REFERENCES sections_cms(id),
    titre VARCHAR(255) NOT NULL,
    description TEXT,
    lien VARCHAR(512),
    ordre_affichage INTEGER NOT NULL DEFAULT 0,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE medias_cms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES documents(id),
    legende VARCHAR(255),
    ordre_affichage INTEGER NOT NULL DEFAULT 0,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE versions_cms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id BIGINT NOT NULL REFERENCES pages_cms(id),
    numero INTEGER NOT NULL CHECK (numero > 0),
    contenu_snapshot JSONB NOT NULL,
    statut VARCHAR(20) NOT NULL CHECK (statut IN ('BROUILLON', 'PUBLIE', 'ARCHIVE')),
    est_restauree BOOLEAN NOT NULL DEFAULT FALSE,
    cree_par BIGINT REFERENCES utilisateurs(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (page_id, numero)
);

CREATE TRIGGER trg_pages_cms_date_modification BEFORE UPDATE ON pages_cms FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_sections_cms_date_modification BEFORE UPDATE ON sections_cms FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_cartes_cms_date_modification BEFORE UPDATE ON cartes_cms FOR EACH ROW EXECUTE FUNCTION maj_date_modification();

CREATE INDEX idx_sections_cms_page ON sections_cms(page_id);
CREATE INDEX idx_cartes_cms_section ON cartes_cms(section_id);
CREATE INDEX idx_medias_cms_document ON medias_cms(document_id);
CREATE INDEX idx_versions_cms_page ON versions_cms(page_id);

INSERT INTO pages_cms (code, titre, statut)
SELECT v.code, v.titre, v.statut
FROM (VALUES ('PAGE_ACCUEIL', 'Page d accueil publique', 'BROUILLON')) AS v(code, titre, statut)
WHERE NOT EXISTS (SELECT 1 FROM pages_cms p WHERE p.code = v.code);
