CREATE TABLE journaux_activite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT REFERENCES utilisateurs(id),
    role_id BIGINT REFERENCES roles(id),
    action VARCHAR(100) NOT NULL,
    entite VARCHAR(80),
    entite_id BIGINT,
    adresse_ip VARCHAR(45),
    appareil VARCHAR(255),
    resultat VARCHAR(20) NOT NULL CHECK (resultat IN ('SUCCES', 'ECHEC', 'REFUSE')),
    date_action TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE evenements_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT REFERENCES utilisateurs(id),
    type_evenement VARCHAR(80) NOT NULL,
    entite VARCHAR(80),
    entite_id BIGINT,
    donnees_avant JSONB,
    donnees_apres JSONB,
    date_evenement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE evenements_securite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT REFERENCES utilisateurs(id),
    type_evenement VARCHAR(80) NOT NULL,
    niveau_gravite VARCHAR(20) NOT NULL CHECK (niveau_gravite IN ('FAIBLE', 'MOYEN', 'ELEVE', 'CRITIQUE')),
    adresse_ip VARCHAR(45),
    appareil VARCHAR(255),
    detail TEXT,
    date_evenement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE FUNCTION proteger_tables_audit()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Les tables d audit ne peuvent pas etre modifiees ni supprimees';
END;
$$;

CREATE TRIGGER trg_journaux_activite_proteger BEFORE UPDATE OR DELETE ON journaux_activite FOR EACH ROW EXECUTE FUNCTION proteger_tables_audit();
CREATE TRIGGER trg_evenements_audit_proteger BEFORE UPDATE OR DELETE ON evenements_audit FOR EACH ROW EXECUTE FUNCTION proteger_tables_audit();
CREATE TRIGGER trg_evenements_securite_proteger BEFORE UPDATE OR DELETE ON evenements_securite FOR EACH ROW EXECUTE FUNCTION proteger_tables_audit();

CREATE INDEX idx_journaux_activite_utilisateur ON journaux_activite(utilisateur_id);
CREATE INDEX idx_journaux_activite_date ON journaux_activite(date_action);
CREATE INDEX idx_evenements_audit_utilisateur ON evenements_audit(utilisateur_id);
CREATE INDEX idx_evenements_audit_date ON evenements_audit(date_evenement);
CREATE INDEX idx_evenements_securite_utilisateur ON evenements_securite(utilisateur_id);
CREATE INDEX idx_evenements_securite_date ON evenements_securite(date_evenement);
