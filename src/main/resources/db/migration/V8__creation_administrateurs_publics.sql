CREATE TABLE demandes_administrateurs_publics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    institution_id BIGINT NOT NULL REFERENCES institutions_publiques(id),
    fonction VARCHAR(150) NOT NULL,
    service_departement VARCHAR(150),
    telephone_professionnel VARCHAR(30),
    email_professionnel VARCHAR(255),
    responsabilites TEXT,
    statut VARCHAR(50) NOT NULL DEFAULT 'EN_ATTENTE' CHECK (statut IN ('EN_ATTENTE', 'EN_EXAMEN', 'INFORMATIONS_COMPLEMENTAIRES_REQUISES', 'APPROUVEE', 'REJETEE')),
    motif_rejet TEXT,
    cree_par BIGINT REFERENCES utilisateurs(id),
    modifie_par BIGINT REFERENCES utilisateurs(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE verifications_administrateurs_publics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demande_id BIGINT NOT NULL REFERENCES demandes_administrateurs_publics(id),
    verificateur_utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    resultat VARCHAR(40) NOT NULL CHECK (resultat IN ('CONFORME', 'NON_CONFORME', 'COMPLEMENT_REQUIS')),
    observations TEXT,
    date_verification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE decisions_administrateurs_publics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demande_id BIGINT NOT NULL REFERENCES demandes_administrateurs_publics(id),
    decideur_utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    decision VARCHAR(50) NOT NULL CHECK (decision IN ('APPROUVEE', 'REJETEE', 'INFORMATIONS_COMPLEMENTAIRES_REQUISES')),
    motif TEXT,
    date_decision TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE documents_demandes_administrateurs_publics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demande_id BIGINT NOT NULL REFERENCES demandes_administrateurs_publics(id),
    document_id BIGINT NOT NULL REFERENCES documents(id),
    type_justificatif VARCHAR(100) NOT NULL,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (demande_id, document_id)
);

CREATE TABLE profils_administrateurs_publics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL UNIQUE REFERENCES utilisateurs(id),
    institution_id BIGINT NOT NULL REFERENCES institutions_publiques(id),
    fonction VARCHAR(150),
    service_departement VARCHAR(150),
    telephone_professionnel VARCHAR(30),
    email_professionnel VARCHAR(255),
    statut_professionnel VARCHAR(30) NOT NULL DEFAULT 'ACTIF' CHECK (statut_professionnel IN ('ACTIF', 'SUSPENDU')),
    date_rattachement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TRIGGER trg_demandes_administrateurs_publics_date_modification BEFORE UPDATE ON demandes_administrateurs_publics FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_profils_administrateurs_publics_date_modification BEFORE UPDATE ON profils_administrateurs_publics FOR EACH ROW EXECUTE FUNCTION maj_date_modification();

CREATE INDEX idx_demandes_admin_utilisateur ON demandes_administrateurs_publics(utilisateur_id);
CREATE INDEX idx_demandes_admin_institution ON demandes_administrateurs_publics(institution_id);
CREATE INDEX idx_demandes_admin_statut ON demandes_administrateurs_publics(statut);
CREATE INDEX idx_verifications_admin_demande ON verifications_administrateurs_publics(demande_id);
CREATE INDEX idx_decisions_admin_demande ON decisions_administrateurs_publics(demande_id);
CREATE INDEX idx_documents_demandes_admin_demande ON documents_demandes_administrateurs_publics(demande_id);
CREATE INDEX idx_profils_admin_institution ON profils_administrateurs_publics(institution_id);
