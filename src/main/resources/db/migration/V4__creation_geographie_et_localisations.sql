CREATE TABLE provinces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10) NOT NULL UNIQUE,
    nom VARCHAR(100) NOT NULL,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE communes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    province_id BIGINT NOT NULL REFERENCES provinces(id),
    code VARCHAR(10) NOT NULL,
    nom VARCHAR(100) NOT NULL,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (province_id, code)
);

CREATE TABLE zones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commune_id BIGINT NOT NULL REFERENCES communes(id),
    code VARCHAR(10) NOT NULL,
    nom VARCHAR(100) NOT NULL,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (commune_id, code)
);

CREATE TABLE collines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id BIGINT NOT NULL REFERENCES zones(id),
    code VARCHAR(20) NOT NULL,
    nom VARCHAR(100) NOT NULL,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (zone_id, code)
);

CREATE TABLE localisations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    province_id BIGINT NOT NULL REFERENCES provinces(id),
    commune_id BIGINT NOT NULL REFERENCES communes(id),
    zone_id BIGINT REFERENCES zones(id),
    colline_id BIGINT REFERENCES collines(id),
    adresse VARCHAR(255),
    complement_adresse VARCHAR(255),
    latitude NUMERIC(10, 7),
    longitude NUMERIC(10, 7),
    point_geographique GEOGRAPHY(POINT, 4326),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE FUNCTION maj_point_geographique()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.latitude IS NOT NULL AND NEW.longitude IS NOT NULL THEN
        NEW.point_geographique := ST_SetSRID(ST_MakePoint(NEW.longitude::double precision, NEW.latitude::double precision), 4326)::geography;
    ELSE
        NEW.point_geographique := NULL;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_localisations_point_geographique BEFORE INSERT OR UPDATE ON localisations FOR EACH ROW EXECUTE FUNCTION maj_point_geographique();
CREATE TRIGGER trg_provinces_date_modification BEFORE UPDATE ON provinces FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_communes_date_modification BEFORE UPDATE ON communes FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_zones_date_modification BEFORE UPDATE ON zones FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_collines_date_modification BEFORE UPDATE ON collines FOR EACH ROW EXECUTE FUNCTION maj_date_modification();
CREATE TRIGGER trg_localisations_date_modification BEFORE UPDATE ON localisations FOR EACH ROW EXECUTE FUNCTION maj_date_modification();

CREATE INDEX idx_communes_province ON communes(province_id);
CREATE INDEX idx_zones_commune ON zones(commune_id);
CREATE INDEX idx_collines_zone ON collines(zone_id);
CREATE INDEX idx_localisations_province ON localisations(province_id);
CREATE INDEX idx_localisations_commune ON localisations(commune_id);
CREATE INDEX idx_localisations_point_geographique ON localisations USING GIST (point_geographique);
